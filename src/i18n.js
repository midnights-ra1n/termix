const DICTS = { fr, en, es, de };
let dict = fr;
export let lang = "fr";

export function setLanguage(pref) {
  const sys = (navigator.language || "fr").slice(0, 2);
  lang = pref && pref !== "auto" ? pref : DICTS[sys] ? sys : "en";
  dict = DICTS[lang] || fr;
  document.documentElement.lang = lang;
}

/** t("connecting", "web-1") → "Connexion à web-1…" */
export function t(key, ...args) {
  const s = dict[key] ?? fr[key] ?? key;
  return args.length ? s.replace(/\{(\d)\}/g, (_, i) => args[i] ?? "") : s;
}

